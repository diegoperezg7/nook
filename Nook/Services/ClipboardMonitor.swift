import AppKit

/// Estado del permiso "Pegar desde otras apps" (privacidad del portapapeles, macOS 15.4+).
enum ClipboardAccess: Equatable {
    case allowed
    /// El sistema preguntaria en cada lectura: no se lee hasta que el usuario elija
    /// "Permitir siempre" en Ajustes del Sistema.
    case needsPermission
    case denied

    static var current: ClipboardAccess {
        guard #available(macOS 15.4, *) else { return .allowed }
        switch NSPasteboard.general.accessBehavior {
        case .alwaysDeny: return .denied
        case .ask: return .needsPermission
        default: return .allowed
        }
    }

    static let settingsURL = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")!
}

/// Tipos que gestores de contraseñas y otras apps marcan como privados o efimeros
/// (convencion de nspasteboard.org). Nunca se guardan.
enum ClipboardFilter {
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    static func shouldIgnore(types: [String]) -> Bool {
        types.contains(where: ignoredTypes.contains)
    }

    /// Un mismo copiado de muchos archivos no debe inundar el historial.
    static let maxFilesPerCopy = 10
}

/// Mira el changeCount del portapapeles cada medio segundo (macOS no notifica los
/// cambios) y guarda lo nuevo en el historial.
@MainActor
final class ClipboardMonitor {
    private let store: ItemStore
    private var timer: Timer?
    private var lastChangeCount: Int
    var onAccessChange: ((ClipboardAccess) -> Void)?
    private(set) var access = ClipboardAccess.current {
        didSet { if access != oldValue { onAccessChange?(access) } }
    }

    init(store: ItemStore) {
        self.store = store
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func poll() {
        let pasteboard = NSPasteboard.general
        access = ClipboardAccess.current
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard pasteboard.changeCount != store.ownChangeCount,
              UserDefaults.standard.bool(forKey: SettingsKey.captureClipboard),
              access == .allowed else { return }

        let types = (pasteboard.types ?? []).map(\.rawValue)
        guard !ClipboardFilter.shouldIgnore(types: types) else { return }

        // La app activa al detectar el cambio es la que copio (se mira cada 0,5 s).
        let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let source = front == Bundle.main.bundleIdentifier ? nil : front

        let urls = pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        if !urls.isEmpty {
            urls.prefix(ClipboardFilter.maxFilesPerCopy).forEach { store.captureFile($0, source: source) }
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            Task { await store.captureImage(data, source: source) }
        } else if let text = pasteboard.string(forType: .string) {
            store.captureText(text, source: source)
        }
    }
}
